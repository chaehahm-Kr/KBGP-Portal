-- 0034_pricing_presets_exchange_rates.sql — Business Preset 및 Exchange Rates 히스토리 도입

BEGIN;

-- 1. 비즈니스 프리셋 테이블 생성
CREATE TABLE IF NOT EXISTS public.pricing_presets (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  code TEXT NOT NULL UNIQUE,
  description TEXT,
  recommended_use_case TEXT,
  applicable_channel TEXT NOT NULL DEFAULT 'both' CHECK (applicable_channel IN ('b2b', 'amazon', 'both')),
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  is_system BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. 시나리오 값 테이블에 preset_id 컬럼 추가 (기존 데이터 호환을 위해 Nullable)
ALTER TABLE public.pricing_scenario_values ADD COLUMN IF NOT EXISTS preset_id UUID REFERENCES public.pricing_presets (id) ON DELETE CASCADE;

-- 기존 (scenario_id, item_id) 단일 유니크 제약조건 제거 및 3차원 (preset_id, scenario_id, item_id) 유니크 제약조건 추가
ALTER TABLE public.pricing_scenario_values DROP CONSTRAINT IF EXISTS pricing_scenario_values_scenario_id_item_id_key;
ALTER TABLE public.pricing_scenario_values DROP CONSTRAINT IF EXISTS pricing_scenario_values_preset_scenario_item_key;

-- NULL을 포함한 유니크 제약조건을 다루기 위한 유니크 인덱스 생성 (preset_id가 NULL인 경우와 지정된 경우 모두 커버)
CREATE UNIQUE INDEX IF NOT EXISTS pricing_scenario_values_preset_scenario_item_idx 
  ON public.pricing_scenario_values (COALESCE(preset_id, '00000000-0000-0000-0000-000000000000'), scenario_id, item_id);

-- 2-1. 계산 기록 테이블에 프리셋 및 환율 정보 컬럼 추가
ALTER TABLE public.pricing_calculations ADD COLUMN IF NOT EXISTS preset_id UUID REFERENCES public.pricing_presets (id) ON DELETE SET NULL;
ALTER TABLE public.pricing_calculations ADD COLUMN IF NOT EXISTS original_supplier_price NUMERIC;
ALTER TABLE public.pricing_calculations ADD COLUMN IF NOT EXISTS original_currency TEXT CHECK (original_currency IN ('KRW', 'USD'));
ALTER TABLE public.pricing_calculations ADD COLUMN IF NOT EXISTS exchange_rate_date TEXT;
ALTER TABLE public.pricing_calculations ADD COLUMN IF NOT EXISTS exchange_rate_source TEXT;

-- 3. 일자별 고시 매매기준율 캐싱용 exchange_rates 테이블 생성
CREATE TABLE IF NOT EXISTS public.exchange_rates (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  rate_date DATE NOT NULL UNIQUE,
  rate_value NUMERIC(10, 2) NOT NULL,
  source TEXT NOT NULL DEFAULT 'automatic', -- 'automatic', 'manual_global'
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. RLS 활성화 및 보안 정책 설정
ALTER TABLE public.pricing_presets ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.exchange_rates ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS pricing_presets_select ON public.pricing_presets;
DROP POLICY IF EXISTS pricing_presets_all_admin ON public.pricing_presets;
DROP POLICY IF EXISTS exchange_rates_select ON public.exchange_rates;
DROP POLICY IF EXISTS exchange_rates_all_admin ON public.exchange_rates;

CREATE POLICY pricing_presets_select ON public.pricing_presets FOR SELECT TO authenticated USING (TRUE);
CREATE POLICY pricing_presets_all_admin ON public.pricing_presets FOR ALL TO authenticated USING (public.auth_is_admin());

CREATE POLICY exchange_rates_select ON public.exchange_rates FOR SELECT TO authenticated USING (TRUE);
CREATE POLICY exchange_rates_all_admin ON public.exchange_rates FOR ALL TO authenticated USING (public.auth_is_admin());

